/**
 * Serializable pure browser DOM evaluation function (mirrors paladini/vibe-code-detector).
 * Designed to be passed directly to Playwright page.evaluate(evaluateVibeInDom, VIBE_FACTORS).
 */
export function evaluateVibeInDom(factorDefs, rootDoc) {
  const doc = rootDoc || document;
  const factors = factorDefs.map((f) => ({ ...f, detected: false, evidence: null }));
  const html = doc.documentElement?.innerHTML ?? "";
  const htmlLower = html.toLowerCase();

  // 1. Tailwind density
  const allElements = doc.querySelectorAll("*");
  let classCount = 0;
  allElements.forEach((el) => {
    if (typeof el.className === "string" && el.className.trim()) {
      classCount += el.className.trim().split(/\s+/).length;
    }
  });
  const classDensity = classCount / (allElements.length || 1);
  factors[0].detected = classDensity > 4.5 || html.includes("tw-");
  if (factors[0].detected) {
    factors[0].evidence = `avgClasses=${classDensity.toFixed(2)}, elements=${allElements.length}, hasTw=${html.includes("tw-")}`;
  }

  // 2. Shadcn / Radix
  const shadcnMarkers = ["bg-background", "text-foreground", "data-radix-", "data-state=", "rounded-xl", "border-input"];
  const shadcnHits = shadcnMarkers.filter((m) => html.includes(m));
  factors[1].detected = shadcnHits.length >= 3;
  if (factors[1].detected) factors[1].evidence = shadcnHits.join(", ");

  // 3. Lucide icons
  const lucideSvgs = doc.querySelectorAll('svg[class*="lucide"]');
  const hasLucide = html.includes("lucide") || lucideSvgs.length > 0;
  factors[2].detected = hasLucide;
  if (hasLucide) factors[2].evidence = `lucideSvgCount=${lucideSvgs.length}`;

  // 4. Vibe stack combination
  const hasMotion = html.includes("framer-motion") || html.includes("motion-");
  factors[3].detected = hasMotion && (hasLucide || factors[0].detected);
  if (factors[3].detected) factors[3].evidence = "framer-motion + tailwind/lucide";

  // 5. AI IDE & agent markers
  const ideMarkers = [
    "cursor-ignore", "__cursor", "windsurf", "trae-ide",
    "replit-agent", "devin-ai", "claude-code",
    "generated by cursor", "created with cursor",
  ];
  const matchedIde = ideMarkers.filter((m) => htmlLower.includes(m));
  const comments = [];
  (function collectComments(node) {
    if (node.nodeType === 8) comments.push((node.nodeValue ?? "").toLowerCase());
    node.childNodes.forEach(collectComments);
  })(doc);
  const matchedComments = comments.filter((c) =>
    c.includes("ai generated") || c.includes("cursor") || c.includes("vibe") ||
    c.includes("prompt:") || c.includes("generated by"),
  );
  factors[4].detected = matchedIde.length > 0 || matchedComments.length > 0;
  if (factors[4].detected) factors[4].evidence = [...matchedIde, ...matchedComments].slice(0, 3).join(", ");

  // 6. Platform signatures
  const metaGenerator = doc.querySelector('meta[name="generator"]')?.getAttribute("content")?.toLowerCase() ?? "";
  const isAIStudio = html.includes("metadata.json") || html.includes("SPDX-License-Identifier: Apache-2.0");
  const isLovable = html.includes("lovable") || html.includes("gptengineer") || html.includes("lovable-project");
  const isBolt = html.includes("bolt-") || html.includes("stackblitz") || html.includes("bolt.new");
  const isV0 = html.includes("v0.dev") || metaGenerator.includes("v0");
  const isReplit = html.includes("replit.app") || html.includes("replit-agent") || html.includes("replit.com");
  const isVercelAI = html.includes("vercel-ai-sdk") || html.includes("ai.vercel.app");
  factors[5].detected = isAIStudio || isLovable || isBolt || isV0 || isReplit || isVercelAI;

  // 7. Prompt artifact comments
  factors[6].detected = matchedComments.length > 0;

  // 8. Model/Provider metadata
  const providerMarkers = ["openai", "anthropic", "gemini", "claude", "gpt-4", "llama", "spdx-license-identifier"];
  const matchedProviders = providerMarkers.filter((m) => htmlLower.includes(m));
  factors[7].detected = matchedProviders.length > 0;
  if (factors[7].detected) factors[7].evidence = matchedProviders.join(", ");

  // 9. Generic code structure
  const bodyText = (doc.body?.innerText ?? doc.body?.textContent ?? "").toLowerCase();
  const placeholderText = ["feature 1", "feature 2", "feature 3", "lorem ipsum", "bento grid", "card title", "card description"];
  const matchedPlaceholders = placeholderText.filter((t) => bodyText.includes(t));
  factors[8].detected = matchedPlaceholders.length > 0;
  if (factors[8].detected) factors[8].evidence = matchedPlaceholders.join(", ");

  // 10. AI SDK / dependency clues
  const sdkMarkers = ["openai", "langchain", "gpt-engineer", "vercel/ai", "@ai-sdk", "huggingface"];
  const matchedSdk = sdkMarkers.filter((m) => htmlLower.includes(m));
  factors[9].detected = matchedSdk.length > 0;
  if (factors[9].detected) factors[9].evidence = matchedSdk.join(", ");

  // 11, 13, 15: DOM-unavailable factors
  factors[10].detected = false;
  factors[12].detected = false;
  factors[14].detected = false;

  // 12. Default AI UI patterns
  factors[11].detected = html.includes("tabler-icon") || html.includes("bento") || html.includes("heroicon");

  // 14. External AI references
  const externalAIRefs = ["openai.com", "anthropic.com", "v0.dev", "claude.ai", "chat.openai.com"];
  const matchedExt = externalAIRefs.filter((m) => html.includes(m));
  factors[13].detected = matchedExt.length > 0;
  if (factors[13].detected) factors[13].evidence = matchedExt.join(", ");

  let totalScore = factors.reduce((sum, f) => sum + (f.detected ? f.weight : 0), 0);
  if (isAIStudio || isV0 || isLovable || isReplit || matchedIde.length > 0) {
    totalScore = Math.max(90, totalScore);
  }

  return {
    score: Math.min(100, totalScore),
    factors,
    detectedFactors: factors.filter((f) => f.detected),
    metrics: {
      elementCount: allElements.length,
      classCount,
      avgClassesPerElement: Number(classDensity.toFixed(2)),
    },
  };
}

/**
 * Evaluate raw HTML string offline via JSDOM using the exact same DOM heuristic logic.
 */
export function analyzeVibeHtml(html, url = "http://localhost/") {
  const dom = new JSDOM(html, { url });
  try {
    return evaluateVibeInDom(VIBE_FACTORS, dom.window.document);
  } finally {
    dom.window.close();
  }
}
